#!/usr/bin/env python3
"""Generate and verify the ADR index (docs/adrs/README.md). See ADR 0012,
amendment 2026-10-12.

The index is derived, never hand-edited: titles and statuses come from the ADR
files, the enforcing checks from checks/enforcement.config.json, and the
"amended by" links from the ADR texts themselves. The `adr-index` check fails
when the committed file differs from what this module renders, so the index
cannot drift the way hand-kept tables did.

Usage:
  python checks/adr_index.py            # print the index
  python checks/adr_index.py --write    # regenerate docs/adrs/README.md
  python checks/adr_index.py --check    # exit 1 if the file is stale
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADRS = ROOT / "docs" / "adrs"
CONFIG = ROOT / "checks" / "enforcement.config.json"
INDEX_NAME = "README.md"

ADR_FILE = re.compile(r"^(\d{4})-.+\.md$")
STATUS_WORD = re.compile(r"^(Proposed|Accepted|Deferred|Superseded)\b")
# Phrases by which one ADR declares that it changes another. Deliberately
# narrow: "would amend ADR 0010" or "see ADR 0004" are not declarations.
AMEND_PATTERNS = [
    re.compile(r"\bamends\s+ADR\s+(\d{4})", re.IGNORECASE),
    re.compile(r"\bADR\s+(\d{4})\s+\([^)]*—\s*amended\b", re.IGNORECASE),
    re.compile(r"\bsupersedes\s+ADR\s+(\d{4})", re.IGNORECASE),
    re.compile(r"\bSupersedes:\*{0,2}[^.\n]*?\bADR\s+(\d{4})"),
]
IN_FILE_AMENDMENT = re.compile(r"^#{2,3} Amendment \((\d{4}-\d{2}-\d{2})\)", re.MULTILINE)


def adr_files(adr_dir=ADRS):
    """Numbered ADR files only, as [(number, path)] in order."""
    out = []
    for f in sorted(adr_dir.glob("*.md")):
        m = ADR_FILE.match(f.name)
        if m:
            out.append((m.group(1), f))
    return out


def parse_adr(number, path):
    text = path.read_text()
    title = re.search(r"^#\s+ADR\s+\d{4}:\s*(.+?)\s*$", text, re.MULTILINE)
    status_line = ""
    m = re.search(r"^## Status\s*\n+([^\n]+)", text, re.MULTILINE)
    if m:
        status_line = m.group(1).strip().lstrip("> ").strip()
    word = STATUS_WORD.match(status_line)
    status = word.group(1) if word else "Unknown"
    if status == "Superseded":
        by = re.search(r"ADR (\d{4})", status_line)
        if by:
            status = f"Superseded by {by.group(1)}"
    return {
        "number": number,
        "file": path.name,
        "title": title.group(1) if title else path.stem,
        "status": status,
        "text": text,
        "amendment_dates": sorted(IN_FILE_AMENDMENT.findall(text)),
    }


def declared_amendments(adrs):
    """{target_number: sorted([amender_number, ...])} from the ADR texts."""
    known = {a["number"] for a in adrs}
    out = {}
    for a in adrs:
        for pat in AMEND_PATTERNS:
            for target in pat.findall(a["text"]):
                if target != a["number"] and target in known:
                    out.setdefault(target, set()).add(a["number"])
    return {k: sorted(v) for k, v in out.items()}


def missing_backlinks(adrs):
    """[(amender, target)] where the amender declares it amends the target
    but the target never mentions the amender."""
    by_number = {a["number"]: a for a in adrs}
    out = []
    for target, amenders in sorted(declared_amendments(adrs).items()):
        for amender in amenders:
            if not re.search(rf"\bADR[ -]?{amender}\b", by_number[target]["text"]):
                out.append((amender, target))
    return out


def checks_by_adr(config):
    out = {}
    for c in config.get("checks", []):
        for number in re.findall(r"\b(\d{4})\b", c.get("adr", "")):
            out.setdefault(number, []).append((c["id"], c["status"]))
    return out


def render(adr_dir=ADRS, config_path=CONFIG):
    adrs = [parse_adr(n, p) for n, p in adr_files(adr_dir)]
    amended_by = declared_amendments(adrs)
    checks = checks_by_adr(json.loads(config_path.read_text()))
    lines = [
        "<!-- GENERATED by checks/adr_index.py from the ADR files and",
        "     checks/enforcement.config.json. Do not edit by hand.",
        "     Regenerate: python checks/adr_index.py --write -->",
        "",
        "# Architecture Decision Records",
        "",
        "One row per record. This table tells you which record to open; it does not",
        "replace reading it. A record's later `## Amendment` sections and the ADRs",
        "listed under \"Amended by\" override its earlier text.",
        "",
        "| ADR | Decision | Status | Enforced by | Amended by | In-file amendments |",
        "|-----|----------|--------|-------------|------------|--------------------|",
    ]
    for a in adrs:
        enforced = ", ".join(f"`{cid}` ({status})" for cid, status in checks.get(a["number"], []))
        amenders = ", ".join(amended_by.get(a["number"], []))
        dates = a["amendment_dates"]
        in_file = f"{len(dates)}, latest {dates[-1]}" if dates else ""
        lines.append(
            f"| [{a['number']}]({a['file']}) | {a['title']} | {a['status']} | "
            f"{enforced or 'no dedicated check'} | {amenders or '—'} | {in_file or '—'} |"
        )
    lines += [
        "",
        "## Reading the columns",
        "",
        "- **Status** — `Accepted` records are in force. `Superseded` and `Deferred`",
        "  records are history: do not build on them.",
        "- **Enforced by** — checks in `checks/run_checks.py` whose config entry names",
        "  the record. `block` fails CI and stops a Claude Code session from finishing;",
        "  `warn` only reports. \"No dedicated check\" means the record's own",
        "  `## Enforcement` section says what, if anything, covers it.",
        "- **Amended by** — later ADRs that state they amend or supersede part of the",
        "  record. The `adr-amendment-link` check requires the amended record to name",
        "  each of them.",
        "",
        "## Changing a record",
        "",
        "Existing records are append-only (ADR 0012). Append a dated",
        "`## Amendment (YYYY-MM-DD)` section to the end of the file, or write a new",
        "numbered ADR that says which record it amends. Then run",
        "`python checks/adr_index.py --write`.",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    index_path = ADRS / INDEX_NAME
    content = render()
    if "--write" in argv:
        index_path.write_text(content)
        print(f"wrote {index_path.relative_to(ROOT)}")
        return 0
    if "--check" in argv:
        current = index_path.read_text() if index_path.exists() else None
        if current != content:
            print(f"{index_path.relative_to(ROOT)} is missing or stale — run: python checks/adr_index.py --write",
                  file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(content)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
